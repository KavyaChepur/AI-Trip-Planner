import json

import requests
import streamlit as st

BASE_URL = "http://localhost:8000"

st.set_page_config(
    page_title="🌍 Travel Planner Agentic Application",
    page_icon="🌍",
    layout="centered",
    initial_sidebar_state="expanded",
)

st.title("🌍 Travel Planner — Multi-Agent")

# --- session / memory setup -------------------------------------------------
if "user_id" not in st.session_state:
    st.session_state.user_id = "demo-user"
if "thread_id" not in st.session_state:
    st.session_state.thread_id = None  # None => backend starts a new conversation
if "chat_history" not in st.session_state:
    st.session_state.chat_history = []  # list of (role, content)

with st.sidebar:
    st.header("Session")
    st.session_state.user_id = st.text_input("User ID (for long-term memory)", value=st.session_state.user_id)
    if st.button("Start a new trip conversation"):
        st.session_state.thread_id = None
        st.session_state.chat_history = []
        st.rerun()
    if st.session_state.thread_id:
        st.caption(f"Conversation thread: `{st.session_state.thread_id[:8]}...`")
    st.markdown("---")
    st.caption(
        "This app uses a supervisor + specialist multi-agent graph "
        "(research → budget → itinerary → critique) with short-term "
        "conversation memory and long-term per-user preferences."
    )

st.header("How can I help you plan a trip?")

for role, content in st.session_state.chat_history:
    with st.chat_message(role):
        st.markdown(content)

user_input = st.chat_input("e.g. Plan a trip to Goa for 5 days")

if user_input:
    st.session_state.chat_history.append(("user", user_input))
    with st.chat_message("user"):
        st.markdown(user_input)

    with st.chat_message("assistant"):
        progress_box = st.empty()
        answer_box = st.empty()
        seen_steps = []
        final_answer = "No answer returned."
        itinerary = None

        try:
            payload = {
                "question": user_input,
                "user_id": st.session_state.user_id,
                "thread_id": st.session_state.thread_id,
            }
            with requests.post(f"{BASE_URL}/query/stream", json=payload, stream=True, timeout=300) as resp:
                for raw_line in resp.iter_lines(decode_unicode=True):
                    if not raw_line or not raw_line.startswith("data: "):
                        continue
                    event = json.loads(raw_line[len("data: "):])

                    if event["type"] == "thread":
                        st.session_state.thread_id = event["thread_id"]
                    elif event["type"] == "step":
                        seen_steps.append(event["label"])
                        progress_box.info("\n".join(f"- {s}" for s in seen_steps[-6:]))
                    elif event["type"] == "final":
                        final_answer = event.get("answer", final_answer)
                        itinerary = event.get("itinerary")
                        st.session_state.thread_id = event.get("thread_id", st.session_state.thread_id)
                    elif event["type"] == "error":
                        st.error(f"Agent error: {event['error']}")

            progress_box.empty()
            answer_box.markdown(final_answer)

            if itinerary and itinerary.get("total_estimated_cost"):
                st.metric(
                    "Estimated total cost",
                    f"{itinerary['total_estimated_cost']} {itinerary.get('currency', '')}",
                )

        except requests.exceptions.RequestException as e:
            progress_box.empty()
            st.error(f"Could not reach the backend at {BASE_URL}: {e}")

    st.session_state.chat_history.append(("assistant", final_answer))

st.caption(
    "*This travel plan was generated by AI. Please verify prices, operating hours, "
    "and travel/visa requirements before your trip.*"
)
